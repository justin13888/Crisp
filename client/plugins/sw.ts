/**
 * Rsbuild plugin: emits `dist/sw.js` with a precache manifest of everything
 * the build produced plus the files in `public/` (including the
 * `crisp-wasm/` module present at build time). The cache name is a content
 * hash of that list, so any change to any asset ships a new worker.
 */

import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";
import type { RsbuildPlugin } from "@rsbuild/core";

/** One file to precache. */
export interface PrecacheFile {
  /** Absolute URL path, e.g. `/static/js/index.abc123.js`. */
  url: string;
  /** File contents (for the cache-name hash). */
  content: string | Uint8Array;
}

/** The resolved precache manifest. */
export interface Precache {
  /** Sorted, de-duplicated URL paths. */
  urls: string[];
  /** `crisp-precache-<hash>`. */
  cacheName: string;
}

/** Output files that must never be precached. */
export const DEFAULT_EXCLUDE: RegExp[] = [
  /^\/sw\.js$/,
  /\.map$/,
  /\.LICENSE\.txt$/,
  /(^|\/)\.[^/]+$/,
];

/** Builds the precache list and its content-hashed cache name. */
export function buildPrecache(
  files: readonly PrecacheFile[],
  exclude: readonly RegExp[] = DEFAULT_EXCLUDE,
): Precache {
  const byUrl = new Map<string, PrecacheFile>();
  for (const file of files) {
    if (exclude.some((re) => re.test(file.url))) continue;
    byUrl.set(file.url, file);
  }
  const urls = [...byUrl.keys()].sort();
  const hash = createHash("sha256");
  for (const url of urls) {
    const file = byUrl.get(url);
    if (!file) continue;
    hash.update(url);
    hash.update("\0");
    hash.update(createHash("sha256").update(file.content).digest());
  }
  return {
    urls,
    cacheName: `crisp-precache-${hash.digest("hex").slice(0, 16)}`,
  };
}

/** Lists every file under `dir` as URL paths rooted at `/`. */
export function listPublicFiles(dir: string): PrecacheFile[] {
  if (!existsSync(dir)) return [];
  const out: PrecacheFile[] = [];
  const walk = (current: string): void => {
    for (const name of readdirSync(current).sort()) {
      const path = join(current, name);
      if (statSync(path).isDirectory()) walk(path);
      else {
        out.push({
          url: `/${relative(dir, path).split(sep).join("/")}`,
          content: readFileSync(path),
        });
      }
    }
  };
  walk(dir);
  return out;
}

/** Renders the final worker: build constants followed by the runtime. */
export function renderServiceWorker(
  precache: Precache,
  runtime: string,
): string {
  return [
    "// Generated by plugins/sw.ts — do not edit.",
    `const CACHE_NAME = ${JSON.stringify(precache.cacheName)};`,
    `const PRECACHE_URLS = ${JSON.stringify(precache.urls, null, 2)};`,
    runtime,
  ].join("\n");
}

/** Plugin options. */
export interface ServiceWorkerOptions {
  /** The public directory (default `<root>/public`). */
  publicDir?: string;
  /** The runtime source (default `plugins/sw-runtime.js`). */
  runtimePath?: string;
  /** Output name (default `sw.js`). */
  filename?: string;
}

/** The rsbuild plugin. Only runs for production builds. */
export function pluginServiceWorker(
  options: ServiceWorkerOptions = {},
): RsbuildPlugin {
  return {
    name: "crisp:service-worker",
    setup(api) {
      const filename = options.filename ?? "sw.js";
      api.processAssets(
        { stage: "report" },
        ({ assets, compilation, sources, environment }) => {
          if (environment.config.mode !== "production") return;
          const root = api.context.rootPath;
          const publicDir = options.publicDir ?? join(root, "public");
          const runtimePath =
            options.runtimePath ?? join(root, "plugins", "sw-runtime.js");

          const emitted: PrecacheFile[] = Object.entries(assets).map(
            ([name, source]) => {
              const raw = source.source();
              return {
                url: `/${name}`,
                content: typeof raw === "string" ? raw : new Uint8Array(raw),
              };
            },
          );
          const precache = buildPrecache([
            ...listPublicFiles(publicDir),
            ...emitted,
          ]);
          const code = renderServiceWorker(
            precache,
            readFileSync(runtimePath, "utf8"),
          );
          compilation.emitAsset(filename, new sources.RawSource(code));
          api.logger.info(
            `[sw] ${filename}: ${precache.urls.length} files precached as ${precache.cacheName}`,
          );
        },
      );
    },
  };
}
