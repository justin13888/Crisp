//! # crisp-wasm
//!
//! The web client's engine, compiled to WebAssembly: `crisp-core` (format,
//! cryptography, verification, rendering) plus the spargen-generated client
//! for the Crisp server's OpenAPI contract (`spec/openapi.json`).
//!
//! Everything a UI needs crosses this boundary already validated and typed:
//! bytes go in, render-ready values come out, and secret keys never leave
//! WASM memory. TypeScript declarations are generated from the Rust types,
//! so the client cannot drift from the format.

#![deny(missing_docs)]

mod boundary;
pub mod format;
pub mod identity;
pub mod server;

/// The Rust client generated by spargen from `spec/openapi.json`.
#[allow(missing_docs, clippy::all, clippy::pedantic, unreachable_pub)]
pub mod api {
    include!(concat!(env!("OUT_DIR"), "/api.rs"));
}

use wasm_bindgen::prelude::wasm_bindgen;

/// Installs a panic hook that surfaces Rust panics in the browser console.
#[wasm_bindgen(start)]
pub fn start() {
    console_error_panic_hook::set_once();
}

#[wasm_bindgen(typescript_custom_section)]
const TS_SHARED: &str = r#"
/** An exact rational number: `[numerator, denominator]`, denominator >= 1. */
export type Rational = [number, number];

/** A failure thrown by any crisp-wasm function. */
export interface CrispFailure extends Error {
  /** A stable verification code such as `E.REF`, when there is one. */
  code?: string;
  /** The HTTP status, for server failures. */
  status?: number;
  /** Every located problem, for draft validation failures. */
  issues?: Issue[];
}
"#;
